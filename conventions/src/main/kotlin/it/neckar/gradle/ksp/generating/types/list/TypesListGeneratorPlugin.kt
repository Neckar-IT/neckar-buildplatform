package it.neckar.gradle.ksp.generating.types.list


import it.neckar.projects.common.MavenCoordinate
import com.google.devtools.ksp.gradle.KspExtension
import it.neckar.gradle.ksp.BaseKspPlugin
import it.neckar.gradle.ksp.options.KspPluginOptions
import org.gradle.api.Project
import org.gradle.api.artifacts.Configuration
import org.gradle.api.provider.Property
import org.gradle.kotlin.dsl.assign
import org.gradle.kotlin.dsl.create
import org.gradle.kotlin.dsl.register
import it.neckar.gradle.pathAsBaseFileName

/**
 * Configure KSP types list generator plugin.
 *
 * The list files:
 * * `it.neckar.gradle.ksp.generating.types.list.TypesListGeneratorPlugin.FileNamePackageNames`
 * * `it.neckar.gradle.ksp.generating.types.list.TypesListGeneratorPlugin.FileNameClassNames`
 * are generated by the KSP plugin.
 *
 * The task `it.neckar.gradle.ksp.generating.types.list.CreateTypesListJsonTask` named (`it.neckar.gradle.ksp.generating.types.list.TypesListGeneratorPlugin.CreateTypesListJsonTaskName`)
 * reads the files and creates a JSON file containing the information.
 */
class TypesListGeneratorPlugin : BaseKspPlugin() {
  override val kspProcessor: MavenCoordinate = MavenCoordinate("it.neckar.open.ksp", "types-list-generator")

  override fun applyCustom(target: Project, kspExtension: KspExtension, configurations: List<Configuration>) {
    super.applyCustom(target, kspExtension, configurations)

    //register the extension
    val extension = target.extensions.create<TypesListGeneratorPluginExtension>(ExtensionName).apply {
      packageNamesListFileName = packageNamesListFileName(target)
      classNamesListFileName = classNamesListFileName(target)
    }

    kspExtension.arg {
      listOf(
        //The file name for the TypeScript definition (usually `index.d.ts`)
        //Is retrieved by [it.neckar.ksp.ts.TypeScriptDefinitionGenerationProcessor]
        KspPluginOptions.TypesListGenerator.PackageNamesListFileName.withValue(extension.packageNamesListFileName.get()),
        KspPluginOptions.TypesListGenerator.ClassNamesListFileName.withValue(extension.classNamesListFileName.get()),
      )
    }

    val createTypesListJsonTask = target.tasks.register<CreateTypesListJsonTask>(CreateTypesListJsonTaskName) {
      group = "ksp"
      description = "Provides the types list"
      projectPath = target.path
      targetFileName = "${target.pathAsBaseFileName()}.json"

      val basePath = "generated/ksp/js/jsMain/resources/it/neckar/types"

      packageNamesListFile.set(target.provider {
        target.layout.buildDirectory.file("$basePath/${extension.packageNamesListFileName.get()}").get()
      })
      classNamesListFile.set(target.provider {
        target.layout.buildDirectory.file("$basePath/${extension.classNamesListFileName.get()}").get()
      })

      targetDirectory = target.layout.buildDirectory.dir("types-lists")
    }

    // Use lazy task configuration to avoid triggering KMP task realization during configuration phase.
    // Using tasks.configureEach with matching instead of iterating over all tasks avoids
    // forcing task creation which would trigger kmpPartiallyResolvedDependenciesChecker
    // and cause "Resolution without exclusive lock" errors.
    target.tasks.configureEach {
      if (name.startsWith("compileKotlin")) {
        finalizedBy(createTypesListJsonTask)
      }
    }

    createTypesListJsonTask.configure {
      // Use matching to lazily depend on compile tasks without forcing their creation
      dependsOn(target.tasks.matching { it.name.startsWith("compileKotlin") })
    }

    target.tasks.getByName("build").dependsOn(createTypesListJsonTask)
  }

  companion object {
    const val ExtensionName: String = "typesListGenerator"

    const val CreateTypesListJsonTaskName: String = "createTypesListJson"

    fun packageNamesListFileName(project: Project): String = "${project.pathAsBaseFileName()}-Packages.list"
    fun classNamesListFileName(project: Project): String = "${project.pathAsBaseFileName()}-ClassNames.list"
  }
}

/**
 * The extension for the types-list generator plugin
 */
interface TypesListGeneratorPluginExtension {
  val packageNamesListFileName: Property<String>
  val classNamesListFileName: Property<String>
}


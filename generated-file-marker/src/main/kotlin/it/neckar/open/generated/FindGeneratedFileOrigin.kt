package it.neckar.open.generated

/**
 * Lines of a file head that a marker may occupy. `check_file_edit` in
 * `.claude/hooks/pre-tool-use-guard.sh` reads the same number.
 */
const val GeneratedFileHeadLineCount: Int = 12

private val commentMarkerLine: Regex = Regex("""^\s*(?://|#|<!--)\s*GENERATED by (.+?) — do not edit by hand\.""")
private val commentSourceLine: Regex = Regex("""^\s*(?://|#|<!--)\s*Source: (.+?)(?:\s*-->)?$""")
private val annotationBy: Regex = Regex("""\bby\s*=\s*"([^"]*)"""")
private val annotationFrom: Regex = Regex("""\bfrom\s*=\s*"([^"]*)"""")

/**
 * The origin stated in the first [GeneratedFileHeadLineCount] lines of [text], read from the comment
 * marker or from `@file:Generated(by =, from =)`; null for a hand-written file.
 */
fun findGeneratedFileOrigin(text: String): GeneratedFileOrigin? {
  val head = text.lineSequence().take(GeneratedFileHeadLineCount).toList()

  val annotationStart = head.indexOfFirst { it.startsWith("@file:Generated(") }
  if (annotationStart >= 0) {
    val annotation = head.drop(annotationStart).takeUntilClosingParenthesis()
    val by = annotationBy.find(annotation)?.groupValues?.get(1) ?: return null
    // `Generated.from` defaults to the empty string for a file without a single input.
    val from = annotationFrom.find(annotation)?.groupValues?.get(1)?.takeUnless { it.isEmpty() }
    return GeneratedFileOrigin(by = by, source = from)
  }

  val (markerIndex, by) = head.withIndex().firstNotNullOfOrNull { (index, line) ->
    commentMarkerLine.find(line)?.let { index to it.groupValues[1] }
  } ?: return null
  val source = head.drop(markerIndex + 1).firstNotNullOfOrNull { commentSourceLine.find(it)?.groupValues?.get(1) }
  return GeneratedFileOrigin(by = by, source = source)
}

/** The lines of an annotation, from its first line up to the one closing it, joined. */
private fun List<String>.takeUntilClosingParenthesis(): String {
  val closing = indexOfFirst { it.trimEnd().endsWith(")") }
  return (if (closing >= 0) take(closing + 1) else this).joinToString("\n")
}

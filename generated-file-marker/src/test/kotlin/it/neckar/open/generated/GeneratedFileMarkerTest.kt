package it.neckar.open.generated

import assertk.*
import assertk.assertions.*
import org.junit.jupiter.api.Test

class GeneratedFileMarkerTest {
  @Test
  fun prependToKeepsAShebangWithoutLineBreakOnLine1() {
    assertThat(
      GeneratedFileMarker(by = "generateScript", source = "script.template", regenerateHint = "Re-run the task.")
        .prependTo("#!/bin/sh", GeneratedFileCommentSyntax.NumberSign)
    ).isEqualTo(
      """
        |#!/bin/sh
        |# GENERATED by generateScript — do not edit by hand.
        |# Source: script.template
        |# Re-run the task.
        |
      """.trimMargin()
    )
  }

  @Test
  fun frontMatterOutsideYamlIsRejected() {
    assertFailure {
      GeneratedFileMarker(by = "generateDocs", source = "docs.template.md", regenerateHint = "Re-run the task.")
        .prependTo("---\ntitle: Docs\n---\n", GeneratedFileCommentSyntax.XmlComment)
    }.hasMessage("a content starting with --- takes the marker as YAML comment, not as XmlComment")
  }

  @Test
  fun blankByIsRejected() {
    assertFailure {
      GeneratedFileMarker(by = " ", source = "products-catalog.yaml", regenerateHint = "Re-run the task.")
    }.hasMessage("generator name must not be blank")
  }

  @Test
  fun blankSourceIsRejected() {
    assertFailure {
      GeneratedFileMarker(by = "generateSomething", source = " ", regenerateHint = "Re-run the task.")
    }.hasMessage("source must not be blank — 'do not edit' is half an instruction, the other half is where the edit belongs")
  }

  @Test
  fun blankRegenerateHintIsRejected() {
    assertFailure {
      GeneratedFileMarker(by = "generateSomething", source = "products-catalog.yaml", regenerateHint = "")
    }.hasMessage("regenerate hint must not be blank")
  }
}

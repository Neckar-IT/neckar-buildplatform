package it.neckar.open.generated

import assertk.*
import assertk.assertions.*
import org.junit.jupiter.api.Test

class FindGeneratedFileOriginTest {
  /** The compiler accepts every spacing around `=`, so the reader does as well. */
  @Test
  fun annotationWithoutSpacesAroundTheEqualsSign() {
    assertThat(findGeneratedFileOrigin("@file:Generated(by=\"spec-generator\", from=\"specs/01-domain/entities/Widget.yaml\")\n\npackage x\n"))
      .isEqualTo(GeneratedFileOrigin(by = "spec-generator", source = "specs/01-domain/entities/Widget.yaml"))
  }

  @Test
  fun commentMarkerWithoutSourceLine() {
    assertThat(findGeneratedFileOrigin("# GENERATED by some-generator — do not edit by hand.\nkey: value\n"))
      .isEqualTo(GeneratedFileOrigin(by = "some-generator", source = null))
  }

  @Test
  fun markerOnTheLastHeadLine() {
    val text = "\n".repeat(GeneratedFileHeadLineCount - 1) + "// GENERATED by some-generator — do not edit by hand.\n"

    assertThat(findGeneratedFileOrigin(text)).isEqualTo(GeneratedFileOrigin(by = "some-generator", source = null))
  }

  @Test
  fun annotationWithAnEmptyFromNamesNoSource() {
    assertThat(findGeneratedFileOrigin("@file:Generated(by = \"spec-generator\", from = \"\")\n\npackage x\n"))
      .isEqualTo(GeneratedFileOrigin(by = "spec-generator", source = null))
  }
}
